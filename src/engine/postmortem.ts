import { t } from './messages.ts';
import type { Locale, LocalizedText, Scenario } from './schema.ts';
import { computeScore } from './scoring.ts';
import type { GameState, HistoryKind } from './types.ts';

/** One line of the postmortem timeline. */
export interface TimelineEntry {
  /** 1-based order of submission. */
  readonly seq: number;
  readonly input: string;
  readonly kind: HistoryKind;
  readonly note?: LocalizedText;
  readonly recovered: boolean;
}

// ---- Labels ----

